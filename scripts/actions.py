"""
actions.py — Generate rule-based action items from metrics and data.

Actions are deterministic (rule-based), NOT generated by LLM.
The LLM may draft the message text for each action, but the trigger
and priority are determined by code.
"""

from dataclasses import dataclass, asdict, field
from typing import Optional


@dataclass
class ActionItem:
    id: str
    priority: str  # "critical" | "high" | "medium" | "low"
    category: str  # "payment" | "stock" | "data_quality" | "expense" | "verification"
    title: str
    description: str
    affected_records: list  # row_ids
    suggested_action: str
    draft_needed: bool  # Whether to draft a message
    draft_recipient: str = ""
    draft_context: dict = field(default_factory=dict)
    
    def to_dict(self):
        return asdict(self)


# Default stock threshold (can be overridden)
DEFAULT_STOCK_THRESHOLD = 10
# Default expense alert threshold (percentage of revenue)
DEFAULT_EXPENSE_ALERT_PCT = 40  # If expenses > 40% of revenue


def generate_actions(
    metrics,
    records: list[dict],
    issues: list,
    stock_threshold: int = DEFAULT_STOCK_THRESHOLD,
    expense_alert_pct: float = DEFAULT_EXPENSE_ALERT_PCT,
) -> list[ActionItem]:
    """Generate action items based on rules."""
    actions = []
    action_counter = 0
    
    def next_id():
        nonlocal action_counter
        action_counter += 1
        return f"ACT-{action_counter:03d}"
    
    # === RULE 1: Unpaid orders → Follow up ===
    if metrics.unpaid_count > 0:
        unpaid_records = [r for r in records if r["type"] == "order" and r["payment_status"] == "unpaid"]
        
        # Group by customer for consolidated follow-up
        by_customer = {}
        for r in unpaid_records:
            cust = r["customer"] or "(unknown customer)"
            if cust not in by_customer:
                by_customer[cust] = []
            by_customer[cust].append(r)
        
        for customer, cust_records in by_customer.items():
            total_unpaid = sum(r["total"] for r in cust_records)
            actions.append(ActionItem(
                id=next_id(),
                priority="high",
                category="payment",
                title=f"Follow up unpaid orders: {customer}",
                description=(
                    f"{len(cust_records)} unpaid order(s) from {customer}, "
                    f"total Rp {total_unpaid:,.0f}. "
                    f"Order dates: {', '.join(r['date'] for r in cust_records if r['date'])}"
                ),
                affected_records=[r["row_id"] for r in cust_records],
                suggested_action="Contact customer to request payment",
                draft_needed=True,
                draft_recipient=customer,
                draft_context={
                    "customer": customer,
                    "total_unpaid": total_unpaid,
                    "order_count": len(cust_records),
                    "orders": [{"date": r["date"], "product": r["product"], 
                               "amount": r["total"]} for r in cust_records],
                }
            ))
    
    # === RULE 2: Partial payments → Follow up ===
    if metrics.partial_count > 0:
        partial_records = [r for r in records if r["type"] == "order" and r["payment_status"] == "partial"]
        for r in partial_records:
            actions.append(ActionItem(
                id=next_id(),
                priority="medium",
                category="payment",
                title=f"Follow up partial payment: {r['customer'] or 'unknown'}",
                description=(
                    f"Order for {r['product']} (Rp {r['total']:,.0f}) has partial payment status. "
                    f"Row {r.get('_source_row', '?')} in source file."
                ),
                affected_records=[r["row_id"]],
                suggested_action="Verify remaining balance and contact customer",
                draft_needed=True,
                draft_recipient=r["customer"] or "",
                draft_context={
                    "customer": r["customer"],
                    "product": r["product"],
                    "amount": r["total"],
                    "date": r["date"],
                }
            ))
    
    # === RULE 3: Data quality errors ===
    error_issues = [i for i in issues if i.severity == "error"]
    if error_issues:
        actions.append(ActionItem(
            id=next_id(),
            priority="critical",
            category="data_quality",
            title=f"Fix {len(error_issues)} data error(s)",
            description=(
                f"{len(error_issues)} record(s) have critical errors and were excluded from processing: "
                + "; ".join(f"Row {i.source_row}: {i.detail}" for i in error_issues[:3])
                + ("..." if len(error_issues) > 3 else "")
            ),
            affected_records=[i.row_id for i in error_issues],
            suggested_action="Review source data and correct errors before reprocessing",
            draft_needed=False,
        ))
    
    # === RULE 4: Outlier values → Verify ===
    outlier_issues = [i for i in issues if "outlier" in i.issue]
    if outlier_issues:
        actions.append(ActionItem(
            id=next_id(),
            priority="medium",
            category="verification",
            title=f"Verify {len(outlier_issues)} unusual transaction(s)",
            description=(
                f"{len(outlier_issues)} transaction(s) have values significantly different from average: "
                + "; ".join(f"Row {i.source_row}: {i.detail}" for i in outlier_issues[:3])
                + ("..." if len(outlier_issues) > 3 else "")
            ),
            affected_records=[i.row_id for i in outlier_issues],
            suggested_action="Confirm these transactions are legitimate",
            draft_needed=False,
        ))
    
    # === RULE 5: Duplicate detection ===
    dup_issues = [i for i in issues if i.issue == "duplicate"]
    if dup_issues:
        actions.append(ActionItem(
            id=next_id(),
            priority="high",
            category="data_quality",
            title=f"Review {len(dup_issues)} potential duplicate(s)",
            description=(
                f"{len(dup_issues)} record(s) appear to be duplicates "
                f"(same date, product, and total as another row): "
                + "; ".join(f"Row {i.source_row}" for i in dup_issues[:5])
            ),
            affected_records=[i.row_id for i in dup_issues],
            suggested_action="Remove duplicates if they are genuine double-entries",
            draft_needed=False,
        ))
    
    # === RULE 6: Low stock alert ===
    # Estimate stock: sum of stock_in quantities minus sum of order quantities
    stock_product = {}
    for r in records:
        product = r["product"]
        if product not in stock_product:
            stock_product[product] = {"in": 0, "out": 0}
        if r["type"] == "stock_in":
            stock_product[product]["in"] += r["quantity"]
        elif r["type"] == "order":
            stock_product[product]["out"] += r["quantity"]
    
    for product, data in stock_product.items():
        estimated_stock = data["in"] - data["out"]
        if data["in"] > 0 and estimated_stock < stock_threshold:
            actions.append(ActionItem(
                id=next_id(),
                priority="high" if estimated_stock <= 0 else "medium",
                category="stock",
                title=f"Reorder stock: {product}",
                description=(
                    f"Estimated remaining stock for '{product}': {estimated_stock:.0f} units "
                    f"(threshold: {stock_threshold}). "
                    f"Stock in: {data['in']:.0f}, Sold: {data['out']:.0f}."
                ),
                affected_records=[],
                suggested_action=f"Contact supplier to reorder {product}",
                draft_needed=True,
                draft_recipient="(supplier)",
                draft_context={
                    "product": product,
                    "estimated_stock": estimated_stock,
                    "threshold": stock_threshold,
                    "sold_today": data["out"],
                }
            ))
    
    # === RULE 7: High expense ratio alert ===
    if metrics.total_revenue > 0 and metrics.total_expenses > 0:
        expense_ratio = (metrics.total_expenses / metrics.total_revenue) * 100
        if expense_ratio > expense_alert_pct:
            actions.append(ActionItem(
                id=next_id(),
                priority="medium",
                category="expense",
                title=f"Expense ratio high: {expense_ratio:.1f}%",
                description=(
                    f"Total expenses (Rp {metrics.total_expenses:,.0f}) are {expense_ratio:.1f}% "
                    f"of total revenue (Rp {metrics.total_revenue:,.0f}). "
                    f"Threshold: {expense_alert_pct}%."
                ),
                affected_records=[],
                suggested_action="Review expense categories and identify cost-saving opportunities",
                draft_needed=False,
            ))
    
    # Sort by priority
    priority_order = {"critical": 0, "high": 1, "medium": 2, "low": 3}
    actions.sort(key=lambda a: priority_order.get(a.priority, 9))
    
    return actions
